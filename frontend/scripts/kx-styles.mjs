// Builds src/kx/css/styles.css: the reference's global stylesheet
// (public/kingexch/css/styles.css), confined to the kingexch components.
//
// Every selector's subject gets `:where([data-kx], [data-kx] *)`, so a rule
// matches only inside a kingexch root and weighs exactly what it does in the
// reference (the inverse of scripts/isolate-kx.js). Left out:
//   - :root (theme.css has the variables) and the dark theme, which the
//     reference never turns on;
//   - bare html/body rules: our <body> is still the old UI's, and what the
//     reference body passes down by inheritance is in kx-base.css;
//   - the FA5 @import (css/fa5.css).
//
//   node scripts/kx-styles.mjs
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import postcss from 'postcss';
import { insertionPoint } from './isolate-kx.js';

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'public/kingexch/css/styles.css');
const OUT = path.join(ROOT, 'src/kx/css/styles.css');
const GUARD = ':where([data-kx], [data-kx] *)';

const scope = (sel) => {
  if (/(^|[\s>+~(,])(:root|html)\b|\.dark\b|data-bs-theme=dark/.test(sel)) return null;
  sel = sel.replace(/^body\s+/, '').trim();
  if (/^body\b/.test(sel)) return null;
  const at = insertionPoint(sel);
  return sel.slice(0, at) + GUARD + sel.slice(at);
};

const root = postcss.parse(fs.readFileSync(SRC, 'utf8'));
root.walkAtRules('import', (at) => at.remove());
root.walkComments((c) => c.remove());
root.walkRules((rule) => {
  if (/keyframes$/i.test(rule.parent?.name || '')) return;
  const selectors = rule.selectors.map(scope).filter(Boolean);
  if (selectors.length) rule.selectors = selectors;
  else rule.remove();
});
root.walkAtRules('media', (at) => { if (!at.nodes.length) at.remove(); });
root.walkDecls((d) => {
  d.value = d.value.replace(/url\((['"]?)\.\.\//g, 'url($1/kingexch/');
});

const header = '/* Generated by scripts/kx-styles.mjs from the reference styles.css — do not edit by hand. */\n';
fs.writeFileSync(OUT, header + root.toString().trim() + '\n');
console.log('wrote', path.relative(ROOT, OUT), fs.statSync(OUT).size, 'bytes');
