// Builds src/kx/css/styles.css: the reference's global stylesheet
// (public/kingexch/css/styles.css), confined to the kingexch components.
//
// Every selector's subject gets `:where([data-kx], [data-kx] *)`, so a rule
// matches only inside a kingexch root and weighs exactly what it does in the
// reference (the inverse of scripts/isolate-kx.js). Left out:
//   - :root (theme.css has the variables) and the dark theme, which the
//     reference never turns on;
//   - bare html/body rules: our <body> is still the old UI's, and what the
//     reference body passes down by inheritance is in kx-base.css;
//   - the FA5 @import (css/fa5.css).
//
// The casino site (casino.kingexch111.com — the Universe game pages) has its
// own global stylesheet; its pages are a [data-kc] subtree (still [data-kx], for
// the old-UI isolation and kx-base), so the main sheet skips [data-kc] subtrees
// and --casino builds the casino one, confined to them, into
// src/kx/csite/css/styles.css. Its asset URLs point at public/kingexch/casino-site.
//
//   node scripts/kx-styles.mjs
//   node scripts/kx-styles.mjs --casino
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import postcss from 'postcss';
import { insertionPoint } from './isolate-kx.js';

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const CASINO = process.argv.includes('--casino');
const SRC = path.join(ROOT, CASINO ? 'reference/casino/styles.css' : 'public/kingexch/css/styles.css');
const OUT = path.join(ROOT, CASINO ? 'src/kx/csite/css/styles.css' : 'src/kx/css/styles.css');
const GUARD = CASINO ? ':where([data-kc], [data-kc] *)' : ':where([data-kx], [data-kx] *):where(:not([data-kc], [data-kc] *))';

const scope = (sel) => {
  if (/(^|[\s>+~(,])(:root|html)\b|\.dark\b|data-bs-theme=dark/.test(sel)) return null;
  sel = sel.replace(/^body\s+/, '').trim();
  if (/^body\b/.test(sel)) return null;
  const at = insertionPoint(sel);
  return sel.slice(0, at) + GUARD + sel.slice(at);
};

const root = postcss.parse(fs.readFileSync(SRC, 'utf8'));
root.walkAtRules('import', (at) => at.remove());
root.walkComments((c) => c.remove());
root.walkRules((rule) => {
  if (/keyframes$/i.test(rule.parent?.name || '')) return;
  const selectors = rule.selectors.map(scope).filter(Boolean);
  if (selectors.length) rule.selectors = selectors;
  else rule.remove();
});
root.walkAtRules('media', (at) => { if (!at.nodes.length) at.remove(); });
// url(card.1bcc4686d105bc71.ttf) → url("/kingexch/casino-site/card.ttf")
const casinoAsset = (file) => `/kingexch/casino-site/${file.replace(/\.[0-9a-f]{16}\./, '.').replace(/ /g, '-')}`;
root.walkDecls((d) => {
  d.value = CASINO
    ? d.value.replace(/url\((['"]?)(?!data:)([^)'"]+)\1\)/g, (m, q, file) => `url("${casinoAsset(file)}")`)
    : d.value.replace(/url\((['"]?)\.\.\//g, 'url($1/kingexch/');
});

const header = `/* Generated by scripts/kx-styles.mjs${CASINO ? ' --casino from the casino site' : ' from the reference'} styles.css — do not edit by hand. */\n`;
// The casino sheet ships minified: lay it out one declaration a line.
const depthOf = (n) => { let d = 0; for (let p = n.parent; p && p.type !== 'root'; p = p.parent) d++; return d; };
if (CASINO) {
  root.walk((n) => {
    const pad = '\n' + '  '.repeat(depthOf(n));
    n.raws.before = pad;
    if (n.type === 'decl') { n.raws.between = ': '; return; }
    n.raws.after = pad;
    if (n.type === 'rule') n.raws.between = ' ';
    n.raws.semicolon = true;
  });
}
fs.writeFileSync(OUT, header + root.toString().trim() + '\n');
console.log('wrote', path.relative(ROOT, OUT), fs.statSync(OUT).size, 'bytes');
