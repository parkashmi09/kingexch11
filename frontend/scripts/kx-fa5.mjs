// Builds src/kx/css/fa5.css from the Font Awesome 5.15.4 sheet the kingexch111
// reference loads (public/kingexch/css/fontawesome-5.15.4/css/all.min.css).
//
// The reference runs FA 4.7 and FA 5 side by side, with FA 5 loaded last, so a
// bare `fa fa-x` renders FA 5's glyph unless styles.css pins it back to FA 4
// (it does that for `.fa-sign-in`). The rest of this app is still FA 4 only,
// so FA 5 must not leak out of the rebuilt components:
//   - `.fas/.far/.fab` are FA 5-only classes and stay global;
//   - a bare `.fa` gets FA 5 only inside a `[data-kx]` subtree (every kingexch
//     component root carries that attribute);
//   - every `.fa-<icon>` rule only applies inside `[data-kx]`, so FA 4's own
//     `.fa-<icon>:before` content is untouched everywhere else.
//
//   node scripts/kx-fa5.mjs
import fs from 'node:fs';
import path from 'node:path';
import url from 'node:url';
import postcss from 'postcss';

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), '..');
const SRC = path.join(ROOT, 'public/kingexch/css/fontawesome-5.15.4/css/all.min.css');
const OUT = path.join(ROOT, 'src/kx/css/fa5.css');

const ICON = '[data-kx] ';
// Container classes go on a wrapper, not on the icon, so they can't be gated.
const CONTAINER = /^\.fa-(stack|ul|li)\b/;

const root = postcss.parse(fs.readFileSync(SRC, 'utf8'));
root.walkRules((rule) => {
  if (rule.parent.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
  const selectors = rule.selectors
    .filter((s) => !/\.sr-only/.test(s))
    .map((s) => {
      s = s.replace(/\.fa(?![\w-])/g, '[data-kx] .fa');
      if (/^\.fa-/.test(s) && !CONTAINER.test(s)) s = ICON + s;
      return s;
    });
  if (selectors.length) rule.selectors = selectors;
  else rule.remove();
});
root.walkAtRules('font-face', (at) => {
  at.walkDecls('src', (d) => {
    d.value = d.value.replace(/url\(\.\.\/webfonts\//g, 'url(/kingexch/css/fontawesome-5.15.4/webfonts/');
  });
});

const header = `/* Generated by scripts/kx-fa5.mjs from Font Awesome 5.15.4 — do not edit by hand. */\n`;
root.walkComments((c) => c.remove());
// One rule per line: the source sheet is pretty-printed, which only adds weight.
const css = root.toString().replace(/\s*\n\s*/g, '').replace(/\}/g, '}\n');
fs.writeFileSync(OUT, header + css);
console.log('wrote', path.relative(ROOT, OUT), fs.statSync(OUT).size, 'bytes');
